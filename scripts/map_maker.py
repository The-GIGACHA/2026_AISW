# 1D Spline (s : x) / (s : y)
class Spline:
    # Si(x) = ai + bi(x-xi) + c(x-xi)^2 + di(x-xi)^3 : 부드러운 3차 방정식 얻는 과정 (계수)
    def __init__(self, x, y):
        self.b, self.c, self.d, self.w = [], [], [], []

        self.x = x
        self.y = y

        self.nx = len(x)  # dimension of x
        h = np.diff(x)  # 각 요소들의 간격을 저장 (n개 요소 -> n-1개 차이값)

        # calc coefficient a
        self.a = [iy for iy in y]

        # calc coefficient c
        A = self.__calc_A(h)
        B = self.__calc_B(h)
        self.c = np.linalg.solve(A, B)  # Ax=B 계산

        # calc coefficient b and d
        for i in range(self.nx - 1):
            self.d.append((self.c[i + 1] - self.c[i]) / (3.0 * h[i]))
            self.b.append((self.a[i + 1] - self.a[i]) / h[i]
                          - h[i] * (self.c[i + 1] + 2.0 * self.c[i]) / 3.0)

    # Calc position : 3차방정식 Si(x)
    def calc(self, t):
        if t < self.x[0] or t > self.x[-1]:
            return None
        i = self.__search_index(t)
        dx = t - self.x[i]
        return self.a[i] + self.b[i] * dx + self.c[i] * dx ** 2.0 + self.d[i] * dx ** 3.0

    # Calc first derivative : 2차방정식 Si'(x)
    def calcd(self, t):
        if t < self.x[0] or t > self.x[-1]:
            return None
        i = self.__search_index(t)
        dx = t - self.x[i]
        return self.b[i] + 2.0 * self.c[i] * dx + 3.0 * self.d[i] * dx ** 2.0

    # Calc second derivative : 1차방정식 Si"(x)
    def calcdd(self, t):
        if t < self.x[0] or t > self.x[-1]:
            return None
        i = self.__search_index(t)
        dx = t - self.x[i]
        return 2.0 * self.c[i] + 6.0 * self.d[i] * dx

    # 인덱스 찾기 (bisect는 넣을 자리를 돌려주므로, 추가로 1을 빼야 정확한 인덱스가 얻어짐)
    def __search_index(self, x):
        return bisect.bisect(self.x, x) - 1

    # calc matrix A for spline coefficient c
    def __calc_A(self, h):
        A = np.zeros((self.nx, self.nx))
        A[0, 0] = 1.0
        for i in range(self.nx - 1):
            if i != (self.nx - 2):
                A[i + 1, i + 1] = 2.0 * (h[i] + h[i + 1])
            A[i + 1, i] = h[i]
            A[i, i + 1] = h[i]
        A[0, 1] = 0.0
        A[self.nx - 1, self.nx - 2] = 0.0
        A[self.nx - 1, self.nx - 1] = 1.0
        return A

    # calc matrix B for spline coefficient c
    def __calc_B(self, h):
        B = np.zeros(self.nx)
        for i in range(self.nx - 2):
            B[i + 1] = 3.0 * (self.a[i + 2] - self.a[i + 1]) / h[i + 1] \
                     - 3.0 * (self.a[i + 1] - self.a[i]) / h[i]
        return B


# 2D Spline : (s : x,y)
class Spline2D:
    def __init__(self, x, y):
        self.s = self.__calc_s(x, y)
        self.sx = Spline(self.s, x)
        self.sy = Spline(self.s, y)

    def __calc_s(self, x, y):
        dx = np.diff(x)
        dy = np.diff(y)
        self.ds = [math.sqrt(idx ** 2 + idy ** 2) for (idx, idy) in zip(dx, dy)]
        s = [0]
        s.extend(np.cumsum(self.ds))
        return s

    def calc_position(self, s):
        return self.sx.calc(s), self.sy.calc(s)

    def calc_curvature(self, s):
        dx = self.sx.calcd(s); ddx = self.sx.calcdd(s)
        dy = self.sy.calcd(s); ddy = self.sy.calcdd(s)
        denom = dx*dx + dy*dy
        if denom is None or denom < 1e-6:
            return 0.0
        return (ddy * dx - ddx * dy) / (denom**1.5)

    def calc_yaw(self, s):
        dx = self.sx.calcd(s)
        dy = self.sy.calcd(s)
        return np.degrees(math.atan2(dy, dx))


# x,y 리스트에서 연속한 두 점의 거리가 0, 즉 중복인 구간을 제거
def clean_xy(x, y, eps=1e-6):
    x = np.asarray(x, float)
    y = np.asarray(y, float)
    dx = np.diff(x)
    dy = np.diff(y)
    ds = np.hypot(dx, dy)
    keep = np.r_[True, ds > eps]   # 첫 점은 무조건 True
    return x[keep].tolist(), y[keep].tolist()


