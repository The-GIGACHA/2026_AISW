    # 인덱스 구간별 미션정보 (기본값은 "NORMAL_DRIVING")
    MISSION_ZONES = [
        # (start_idx, end_idx, "MISSION_NAME")
        # (10, 100, "E_STOP"),
    ]

    # 인덱스 구간별 기어정보 ([0:전진, 2:후진 / 기본값은 0] <> 모라이: 1:P 2:R 3:N 4:D / 기본 4)
    GEAR_ZONES = [
        # (start_idx, end_idx, gear)
        (1858, 1860, 1)
    ]

    # 인덱스별 속도 수동설정 (version2 용)
    VELOCITY_ZONES = [
        # (start_idx, end_idx, velocity_mps)
        # (3600, 3730, 20),
        (500, 580, 25),
        (830, 920, 25),
        (1445, 1490, 25),
        (1610, 1657, 15)
        # 본선맵 기준 1657 이후부터는 음영구역
    ]

    ################################################################################################
    if VERSION == 1:
        print("Ver 1...")
        if not xy:
            print("xy is empty...")
            return

        # xy → x, y 리스트로 언팩
        x, y = map(list, zip(*xy))

        # 중복된 거리(s=0) 제거
        x, y = clean_xy(x, y, 1e-6)

        if len(x) < 2:
            print("at least two points are required...")
            return
        if len(x) != len(y):
            print("x and y must have the same number of elements...")
            return

        sp = Spline2D(x, y)
        s = np.arange(0, sp.s[-1], step_size)

        if sp.s[-1] < step_size:
            print("longer path required...")
            return

        rx, ry, ryaw, rk, rvel = [], [], [], [], []
        vel_history = deque(maxlen=window_size)
        data = {}

        for idx, i_s in enumerate(s):
            ix, iy = sp.calc_position(i_s)
            rx.append(ix)
            ry.append(iy)
            yaw_val = sp.calc_yaw(i_s)
            curv_val = sp.calc_curvature(i_s)
            ryaw.append(yaw_val)
            rk.append(curv_val)

            # 곡률기반 속도
            k = abs(curv_val)
            R = float('inf') if k < 1e-6 else (1.0 / k)
            v_fric = max_velocity if R == float('inf') else min((mu * 9.81 * R) ** 0.5, max_velocity)
            vel = v_fric * math.exp(-alpha * k)  # 곡률 민감도 적용

            vel_history.append(vel)
            vel_smooth = round(sum(vel_history) / len(vel_history), 2)
            rvel.append(vel_smooth)

            # 미션정보
            mission = "NORMAL_DRIVING"
            for start, end, name in MISSION_ZONES:
                if start <= idx <= end:
                    mission = name
                    break

            # 기어정보
            gear = 4
            for start, end, g in GEAR_ZONES:
                if start <= idx <= end:
                    gear = g
                    break

            # 저장 데이터
            data[idx] = {
                "x": ix,
                "y": iy,
                "yaw": yaw_val,
                "curvature": curv_val,
                "velocity": vel_smooth,
                "mission": mission,
                "gear": gear
            }

    elif VERSION == 2:
        print("Ver 2...")
        # 1) JSON 읽어오기
        with open(INPUT_JSON, 'r') as f:
            data = json.load(f)

        # 2) 인덱스 정렬
        keys = sorted(data.keys(), key=lambda k: int(k))

        # 3) 시퀀스 추출
        s    = [int(k) * step_size for k in keys]
        rx   = [data[k]['x']         for k in keys]
        ry   = [data[k]['y']         for k in keys]
        ryaw = [data[k]['yaw']       for k in keys]
        rk   = [data[k]['curvature'] for k in keys]
        rvel = [data[k]['velocity']  for k in keys]

        # 4) mission 업데이트
        for k in keys:
            idx = int(k)
            mission = "NORMAL_DRIVING"
            for start, end, name in MISSION_ZONES:
                if start <= idx <= end:
                    mission = name
                    break
            data[k]['mission'] = mission

            # 5) velocity/gear 업데이트
            for v_start, v_end, v in VELOCITY_ZONES:
                if v_start <= idx <= v_end:
                    data[k]['velocity'] = v
                    break
            for g_start, g_end, g in GEAR_ZONES:
                if g_start <= idx <= g_end:
                    data[k]['gear'] = g
                    break

    # 그래프 plot
    flg, ax = plt.subplots(1)
    if VERSION == 1:
        plt.plot(x, y, "xb", label="input")
    elif VERSION == 2:
        plt.plot(rx, ry, "xb", label="index")
    plt.plot(rx, ry, "-r", label="spline")
    plt.grid(True)
    plt.axis("equal")
    plt.xlabel("x [m]")
    plt.ylabel("y [m]")
    plt.legend()

    flg, ax = plt.subplots(1)
    plt.plot(s, ryaw, "-r", label="yaw")
    plt.grid(True)
    plt.legend()
    plt.xlabel("distance [m]")
    plt.ylabel("yaw angle [deg]")

    flg, ax = plt.subplots(1)
    plt.plot(s, rk, "-r", label="curvature")
    plt.grid(True)
    plt.legend()
    plt.xlabel("distance [m]")
    plt.ylabel("curvature [1/m]")

    flg, ax = plt.subplots(1)
    plt.plot(s, rvel, "-r", label="velocity")
    plt.plot(s, rvel, "xb")  # 샘플 포인트 표시 (라벨 중복 제거)
    plt.grid(True)
    plt.legend()
    plt.xlabel("distance [m]")
    plt.ylabel("velocity [m/s]")  # 단위 수정

    plt.show()

    # json파일 저장
    with open(OUTPUT_JSON, 'w') as f:
        json.dump(data, f, indent=4)

    print(f"Data saved to {OUTPUT_JSON}")


